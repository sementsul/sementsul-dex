// Подход 2: собственный yield-bearing пул на BSC. Проверяем по фактам.
//
// ВАЖНО: первая версия этого разбора утверждала, что на BSC нельзя
// делегировать BNB из контракта. Это НЕВЕРНО. По официальной документации
// (docs.bnbchain.org, staking/developer-guide) делегирование открыто любому:
//
//   StakeHub: 0x0000000000000000000000000000000000002002
//   function delegate(address operatorAddress, bool delegateVotePower) payable
//
// То есть контракт биржи МОЖЕТ отправить BNB в стейкинг и получать награды.
// Валидатором для этого быть не нужно — нужен только делегатор.
//
// Значит вопрос не «возможно ли», а «выгодно ли». Разбираем ограничения.

const fmt = (x, d = 2) => Number(x).toLocaleString('ru-RU', { maximumFractionDigits: d })

console.log('=== Подход 2 на BSC: технически возможен, но с тремя барьерами ===\n')

console.log('--- Барьер 1: st-кредит непереводим ---\n')
console.log('При делегировании выдаётся st-кредит (например stBNB48Club):')
console.log('  ✅ представляет застейканный BNB + награды, дорожает сам')
console.log('  ❌ НЕ переводится между адресами (прямо сказано в документации)')
console.log('  ❌ у каждого валидатора свой токен, единого нет')
console.log('\nСледствие: этот токен НЕЛЬЗЯ положить в AMM-пул. Чтобы получить')
console.log('ликвидный инструмент, его нужно обернуть в свой переводимый ERC-20')
console.log('с курсом к BNB. Это ровно то, что уже делают Lista, Ankr и pStake —')
console.log('со своим аудитом, оракулами и историей.')

console.log('\n--- Барьер 2: вывод 7 дней ---\n')
const UNBOND = 7
console.log(`Undelegate → ${UNBOND} дней unbonding → claim.`)
console.log('Для пула это значит: застейканную часть резерва нельзя вернуть')
console.log('по первому требованию. Если LP придут выводить ликвидность,')
console.log('а половина резерва в стейкинге — пул не сможет расплатиться.')
console.log('\nОтсюда ограничение: стейкать можно только «излишек», который')
console.log('с гарантией не понадобится неделю. Считаем сколько это.\n')

const TVL = 100_000
const APY = 0.024 // осторожная оценка; точный APY см. примечание ниже

// Важно: свопы резерв НЕ расходуют — они перекладывают его туда-обратно.
// Ограничение задаёт не объём торгов, а то, сколько LP могут захотеть
// вывести за 7 дней. Поэтому считаем по доле вывода, а не по обороту.
console.log('Ограничение — не оборот, а доля TVL, которую LP могут вывести')
console.log('за 7 дней (столько идёт unbonding). Оборачиваемость тут ни при чём:')
console.log('свопы резерв не тратят, они его перекладывают.\n')
for (const withdrawShare of [0.1, 0.2, 0.3, 0.5]) {
  const needed = TVL * withdrawShare
  const stakeable = TVL - needed
  console.log(
    `  если за неделю выводят ${(withdrawShare * 100).toFixed(0)}% TVL ($${fmt(needed, 0)}), ` +
      `стейкать можно $${fmt(stakeable, 0)} (${((stakeable / TVL) * 100).toFixed(0)}%)`
  )
}
console.log('\nРеалистично: на спокойном пуле за неделю выходит единицы процентов TVL,')
console.log('поэтому застейкать можно большую часть. Но в момент паники или')
console.log('ликвидации позиций выводят всё сразу — и тогда пул не расплатится.')

console.log('\n--- Барьер 3: доход мизерный ---\n')
console.log(`Даже в идеальном случае — половина резерва застейкана при ${(APY * 100).toFixed(1)}%:`)
const gain = 0.5 * APY
console.log(`  прибавка к доходу LP = 0.5 × ${(APY * 100).toFixed(1)}% = ${(gain * 100).toFixed(2)}% годовых от TVL.`)
console.log(`  для пула $${fmt(TVL, 0)} это $${fmt(TVL * gain, 0)}/год.`)
console.log('\nДля сравнения торговая комиссия на том же пуле при обороте 1×TVL/день')
console.log(`и ставке 0.05%: $${fmt(TVL * 365 * 0.0005, 0)}/год.`)
console.log(`Стейкинг даёт ~${((gain / (365 * 0.0005)) * 100).toFixed(0)}% от торговой комиссии —`)
console.log('то есть на порядок меньше. И это до вычета риска слэшинга.')

console.log('\n--- Барьер 4 (главный): конкуренция с готовыми LST ---\n')
console.log('Если мы обернём BNB в собственный LST, он будет конкурировать')
console.log('с slisBNB от Lista, у которого:')
console.log('  • выпущено 946 272 slisBNB ≈ $539 млн (измерено по totalSupply);')
console.log('  • пул slisBNB/WBNB на Pancake V3 0.05% с TVL $2.85 млн (измерено).')
console.log('\nНаш LST с нулевой ликвидностью не даст держателю ничего, кроме')
console.log('лишнего риска нашего контракта. Держатель просто купит slisBNB.')

console.log('\n=== примечание про APY ===')
console.log('Точный APY валидаторов BSC я измерить не смог: системные контракты')
console.log('(0x...2002) не отвечают на eth_call через публичные RPC — вызовы')
console.log('ревертят независимо от сигнатуры. Поэтому здесь взята осторожная')
console.log('оценка 2.4%, и она не влияет на вывод: даже при 10% картина')
console.log('по барьеру 4 не меняется, а барьер 2 становится строже.')

console.log('\n=== вывод ===')
console.log('Подход 2 возможен, но: непереводимый кредит требует своей обёртки,')
console.log('7-дневный вывод ограничивает долю резерва, доход на порядок ниже')
console.log('торговой комиссии, а конкурировать придётся с $539 млн чужого LST.')
console.log('Это не «на вырост» — это отдельный продукт со своим аудитом,')
console.log('и делать его имеет смысл только при TVL в десятки миллионов.')