// Воспроизведение зависания: при каких условиях цикл в пуле не завершается.
//
// На реальном пуле (L ≈ 4.5e21) все суммы дошли до оплаты — зависания нет.
// А в тесте (L = 1e23, цена 1:1) сумма 1e6 вызвала MemoryOOG.
//
// Разница: соотношение суммы к ликвидности и позиция цены относительно
// тиков. Считаем, при каком минимуме цена перестаёт двигаться, для разных L.
//
// Формула из getNextSqrtPriceFromInput (zeroForOne):
//     next = ceil(num1 * sqrtP / (num1 - amount * sqrtP))
// где num1 = L << 96. Если next == sqrtP (в uint160), сдвига нет.
//
// Ищем минимальную сумму, при которой next > sqrtP.

function minAmountForShift(L, sqrtP) {
  // Бинарный поиск по сумме: минимальная, дающая сдвиг хотя бы на 1.
  let lo = 1n
  let hi = 10n ** 24n
  const num1 = BigInt(L) * (1n << 96n)
  const sp = BigInt(sqrtP)

  while (lo < hi) {
    const mid = (lo + hi) / 2n
    const product = mid * sp
    if (num1 <= product) {
      hi = mid
      continue
    }
    const denom = num1 - product
    const next = (num1 * sp + denom - 1n) / denom
    if (next > sp) hi = mid
    else lo = mid + 1n
  }
  return lo
}

const cases = [
  ['тест: L=1e23, цена 1:1', 10n ** 23n, 79228162514264337593543950336n],
  ['реальный пул: L=4.5e21', 4509276405385454871807n, 3348424369061109053090655897n],
  ['реальный пул: L=1e21', 10n ** 21n, 3348424369061109053090655897n],
  ['маленький пул: L=1e18', 10n ** 18n, 79228162514264337593543950336n],
  ['совсем малый: L=1e15', 10n ** 15n, 79228162514264337593543950336n],
]

console.log('  условия                                  мин. сумма для сдвига цены')
for (const [label, L, sp] of cases) {
  const m = minAmountForShift(L, sp)
  console.log(`  ${label.padEnd(40)} ${m.toString()} wei  (${(Number(m) / 1e18).toExponential(2)} в токене)`)
}

