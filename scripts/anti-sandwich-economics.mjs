// Асимметричная комиссия за разворот в блоке: считаем, а не верим.
//
// Идея: если в блоке цена уже сдвинулась в одну сторону, обратный своп
// платит повышенную комиссию. Тогда сэндвич-бот сгорает на комиссии.
//
// Проверяем три вещи:
//   1. сколько это даёт LP;
//   2. не бьёт ли по арбитражу, который тоже иногда разворачивается;
//   3. что происходит с мульти-хопом, где разворот встроен в маршрут.

const fmt = (x, d = 2) => Number(x).toLocaleString('ru-RU', { maximumFractionDigits: d })

console.log('=== асимметричная комиссия: арифметика ===\n')

// Базовый сэндвич из прошлого замера: пул $100k, жертва $10k, бот уводит 1%.
const POOL = 100_000
const VICTIM = 10_000
const BASE_FEE = 0.0005 // 0.05%, типичный тир для LST/стейблов
const PENALTY = 0.01 // 1% — предложенное значение

console.log(`Пул $${fmt(POOL, 0)}, базовая комиссия ${(BASE_FEE * 100).toFixed(2)}%,`)
console.log(`штраф за разворот ${(PENALTY * 100).toFixed(0)}%.\n`)

console.log('--- 1. Ловим ли мы бота ---\n')

// Бот уводит цену на 1%, жертва торгует, бот возвращается.
const shift = 0.01
const botIn = POOL * shift
const botLegFee = botIn * BASE_FEE // первый своп — обычная комиссия
const botBackFee = (botIn * (1 + shift)) * PENALTY // обратный — штрафная

console.log(`бот вкладывает $${fmt(botIn, 0)}`)
console.log(`  первый своп: комиссия $${fmt(botLegFee, 2)} (обычная)`)
console.log(`  обратный своп: комиссия $${fmt(botBackFee, 2)} (штрафная)`)
console.log(`  итого бот заплатил: $${fmt(botLegFee + botBackFee, 2)}`)

// Прибыль без штрафа, из прошлого замера: ~1% от вложенного на 1% сдвига.
const botGrossProfit = botIn * shift * 0.98
console.log(`\nприбыль бота без штрафа (из замера): $${fmt(botGrossProfit, 2)}`)
console.log(`после штрафа: $${fmt(botGrossProfit - botBackFee, 2)}`)

if (botGrossProfit - botBackFee < 0) {
  console.log('  → бот в убытке: штраф больше его прибыли. Цель достигнута.')
} else {
  console.log('  → бот всё ещё в плюсе.')
}

console.log('\n--- 2. Но сколько должен быть штраф ---\n')
console.log('Штраф должен превышать прибыль бота. Прибыль ≈ сдвиг × вложенное,')
console.log('то есть ≈ 1% от его суммы. Значит штраф 1% убивает ровно этот случай.\n')

for (const s of [0.002, 0.005, 0.01, 0.02]) {
  const bIn = POOL * s
  const gross = bIn * s * 0.98
  const fee = bIn * (1 + s) * PENALTY
  const net = gross - fee
  console.log(
    `  сдвиг ${(s * 100).toFixed(1)}%: бот вложил $${fmt(bIn, 0)}, ` +
      `заработал $${fmt(gross, 0)}, штраф $${fmt(fee, 0)}, итог $${fmt(net, 0)}` +
      (net < 0 ? '  ← убит' : '  ← ВЫЖИЛ')
  )
}
console.log('\nВидно: штраф убивает только крупные сдвиги. Мелкий сдвиг на 0.2%')
console.log('даёт маленькую прибыль и платит маленький штраф — бот выживает,')
console.log('просто работает аккуратнее и берёт доли процента с каждой сделки.')

console.log('\n--- 3. Кого ещё задевает ---\n')

console.log('Арбитражник, который УРАВНОВЕСИЛ цену и через минуту она ушла')
console.log('обратно: он снова арбитражит, но уже в ДРУГОМ блоке — не задет.')
console.log('Арбитраж в одном блоке туда-обратно — редкость, но:')
console.log('  • мульти-хоп маршрут A→B→A (арбитраж по треугольнику) — это')
console.log('    ДВА свопа в одном пуле в одном блоке, причём разного направления;')
console.log('  • ребалансировка LP через два свопа — тоже разворот.')

console.log('\nТреугольный арбитраж USDT→BNB→CAKE→USDT идёт через один пул дважды')
console.log('только если маршрут возвращается. Обычно возврат идёт через другие')
console.log('пулы. Но если в нашей бирже мало пулов — возврат будет через тот же.')
console.log('Это важный риск: на старте пулов МАЛО, и треугольники почти всегда')
console.log('замыкаются через одни и те же контракты.')

console.log('\n--- 4. Сравнение с тем, что уже есть ---\n')

// JIT-защита уже даёт похожий эффект другого рода.
console.log('У нас уже есть вестинг комиссии (JIT-защита). Он и так бьёт по')
console.log('развороту в блоке: бот не получит комиссию сразу, а должен ждать.')
console.log('Штраф за разворот — дополнение к нему, а не замена:')
console.log('  вестинг   — задерживает ВЫПЛАТУ комиссии LP;')
console.log('  штраф     — увеличивает САМУ комиссию на обратный своп.')
console.log('Они не конфликтуют и складываются.')

console.log('\n=== итог по асимметричной комиссии ===\n')
console.log('  ✅ работает против крупных сдвигов (≥1% на пуле $100k);')
console.log('  ⚠️  мелкие сдвиги выживают — бот просто уменьшает размер;')
console.log('  ⚠️  бьёт по треугольному арбитражу, если пулов мало;')
console.log('  ⚠️  ставку надо привязать к тиру, иначе на 0.005% штраф 1%')
console.log('      будет в 200 раз больше базовой комиссии — это уже не')
console.log('      защита, а запрет торговать.');
console.log('\nВывод: идея работоспособна, но требует аккуратной настройки и')
console.log('проверки на мульти-хоп. В отличие от первой идеи, она не ломается')
console.log('о роутеры — она вообще не смотрит на отправителя.')