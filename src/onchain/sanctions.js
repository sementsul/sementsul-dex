// Санкционный скрининг внутри on-chain версии.
//
// Задача: интерфейс, который лежит в блокчейне, не может сходить на сервер
// за списком OFAC. Значит список надо вшить в сам HTML. 127 адресов по
// 20 байт — это 5.2 KB, около $0.006 газа. Приемлемо.
//
// Хранение. Не массив строк с кавычками и запятыми (это лишние 3 байта на
// адрес), а одна сплошная строка hex без префиксов 0x. Один адрес занимает
// ровно 40 символов, поэтому проверка сводится к поиску подстроки с
// контролем выравнивания: если index % 40 === 0, совпадение целое.
//
// Почему не хешbloom/префиксы. Экономия была бы ~2 KB, но появились бы
// ложные срабатывания: человек с чистым кошельком увидел бы «адрес под
// санкциями». Для финансового интерфейса это недопустимо, поэтому храним
// полные адреса.
//
// Честное ограничение: список статичен на момент публикации. OFAC обновляет
// SDN несколько раз в месяц. Это барьер, а не гарантия — ровно как и на
// основном сайте, где список обновляется сборкой.

// Список вшивается на этапе сборки: scripts/build-onchain2.mjs подставляет
// его сюда вместо плейсхолдера. Так в исходниках не лежит простыня на 5 KB,
// которую невозможно читать, а в собранном HTML она есть.
export const SANCTIONS_HEX = '__SANCTIONS_HEX__'

// Дата, на которую актуален список. Показывается в интерфейсе: человек
// вправе знать, насколько свежая проверка.
export const SANCTIONS_DATE = '__SANCTIONS_DATE__'

const ADDR_LEN = 40

/// Проверяет адрес по вшитому списку.
///
/// Возвращает true, если адрес найден. Регистр не важен: список и вход
/// приводятся к нижнему.
export function isSanctioned(address) {
  if (typeof address !== 'string' || address.length !== 42) return false
  const needle = address.slice(2).toLowerCase()
  if (needle.length !== ADDR_LEN) return false

  const hay = SANCTIONS_HEX.toLowerCase()
  let from = 0
  for (;;) {
    const i = hay.indexOf(needle, from)
    if (i === -1) return false
    // Совпадение должно начинаться на границе адреса, иначе это случайные
    // 40 символов, пересёкшие границу двух соседних адресов.
    if (i % ADDR_LEN === 0) return true
    from = i + 1
  }
}

/// Сколько адресов во вшитом списке. Нужно для проверки целостности при
/// сборке и для показа в интерфейсе.
export function sanctionsCount() {
  return Math.floor(SANCTIONS_HEX.length / ADDR_LEN)
}

