// Поиск по базе знаний: ищем в заголовках, описаниях и тексте статей.
// Возвращаем статьи целиком — пользователю нужен контекст, а не вырванная
// строка, поэтому подсветку совпадений не делаем.
export function searchArticles(query) {
  const q = query.trim().toLowerCase()
  if (!q) return ARTICLES

  return ARTICLES.filter((a) => {
    const hay = [
      a.title,
      a.summary,
      ...a.tags,
      ...a.body.flatMap((s) => [s.h, ...s.p]),
    ]
      .join(' ')
      .toLowerCase()
    return hay.includes(q)
  })
}

export function getArticle(id) {
  return ARTICLES.find((a) => a.id === id) || null
}